function buildDeck() {
  const deck = [];
  MAJOR_INFO.forEach(([num, cn, en, up, rev, kw]) => {
    deck.push({
      id: `major-${String(num).padStart(2, '0')}`,
      arcana: 'major',
      name: cn,
      en,
      suit: null,
      rank: null,
      upright: up,
      reversed: rev,
      keywords: kw,
      img: `images/cards/major-${String(num).padStart(2, '0')}.svg`,
    });
  });
  Object.keys(SUIT_INFO).forEach((suitKey) => {
    const suit = SUIT_INFO[suitKey];
    RANK_INFO.forEach(([rk, rankCn, up, rev]) => {
      deck.push({
        id: `${suitKey}-${rk}`,
        arcana: 'minor',
        name: `${suit.cn}${rankCn}`,
        en: `${suit.theme}`,
        suit: suitKey,
        rank: rankCn,
        upright: `${suit.theme} · ${up}`,
        reversed: `${suit.theme} · ${rev}`,
        keywords: [suit.cn, rankCn, suit.element],
        img: `images/cards/${suitKey}-${rk}.svg`,
      });
    });
  });
  return deck;
}

const TAROT_DECK = buildDeck();

function shuffleArray(arr) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}